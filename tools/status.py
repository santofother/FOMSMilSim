#!/usr/bin/env python3
"""Status board for FOMS Battle Simulator.

Reads the header block of every card in docs/sessions/ and every handoff in docs/handoffs/,
then prints the board. A card with no handoff is READY when all its dependencies are DONE,
otherwise TODO. A playtest card (agent: User) is DONE when its owned docs/playtests file exists.

    python3 tools/status.py          # print the board
    python3 tools/status.py --write  # also write docs/STATUS.md
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SESSIONS = ROOT / "docs" / "sessions"
HANDOFFS = ROOT / "docs" / "handoffs"


def header(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\s*\n(.*?)\n---", text, re.S)
    if not m:
        return {}
    data = {}
    for line in m.group(1).splitlines():
        line = line.split(" #", 1)[0].rstrip()
        if ":" not in line:
            continue
        key, val = line.split(":", 1)
        val = val.strip()
        if val.startswith("[") and val.endswith("]"):
            val = [v.strip() for v in val[1:-1].split(",") if v.strip()]
        data[key.strip()] = val
    return data


def main() -> None:
    cards = {}
    for p in sorted(SESSIONS.glob("*.md")):
        h = header(p)
        if h.get("card"):
            cards[h["card"]] = h

    handoffs = {}
    extras = []
    for p in sorted(HANDOFFS.glob("*.md")):
        if p.name == "README.md":
            continue
        h = header(p)
        cid = h.get("card") or p.stem
        if cid in cards:
            handoffs[cid] = h
        else:
            extras.append((cid, h))

    def status(cid: str) -> str:
        c = cards[cid]
        if cid in handoffs:
            return handoffs[cid].get("status", "DONE").upper()
        if c.get("agent") == "User":
            owned = [o for o in c.get("owns", []) if isinstance(c.get("owns"), list)]
            if owned and all((ROOT / o).exists() for o in owned):
                return "DONE"
        deps = c.get("depends", [])
        if all(d in cards and status(d) == "DONE" for d in deps):
            return "READY"
        return "TODO"

    phase_rank = {"0": 0, "A": 1, "B": 2, "C": 3, "D": 4}
    kind_rank = {"S": 0, "P": 1, "T": 2}

    def order(cid: str):
        num = int(re.sub(r"\D", "", cid) or 0)
        return (phase_rank.get(cards[cid].get("phase", ""), 9), kind_rank.get(cid[:1], 3), num)

    rows = []
    for cid in sorted(cards, key=order):
        c = cards[cid]
        st = status(cid)
        h = handoffs.get(cid, {})
        note = h.get("date", "")
        if h.get("branch"):
            note = f"{note} {h['branch']}".strip()
        rows.append((c.get("phase", ""), cid, c.get("title", ""), st, c.get("preferred", c.get("agent", "")), c.get("tier", ""),
                     ", ".join(c.get("depends", [])) or "-", ", ".join(c.get("parallel", [])) or "-", note))

    lines = ["| Phase | Card | Title | Status | Preferred model | Tier | Needs | Runs with | Done |",
             "|---|---|---|---|---|---|---|---|---|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    if extras:
        lines += ["", "Other sessions (fixes etc.):", ""]
        lines += [f"- {cid}: {h.get('status', '?')} {h.get('date', '')} {h.get('branch', '')}".rstrip() for cid, h in extras]
    ready = [r[1] for r in rows if r[3] == "READY"]
    summary = f"READY now: {', '.join(ready) if ready else 'nothing'}"
    out = "\n".join(lines) + "\n\n" + summary + "\n"
    print(out)

    if "--write" in sys.argv:
        (ROOT / "docs" / "STATUS.md").write_text(
            "# Status board\n\n*Generated by `python3 tools/status.py --write`. Don't edit by hand: "
            "edit handoff headers instead.*\n\n" + out, encoding="utf-8")


if __name__ == "__main__":
    main()
